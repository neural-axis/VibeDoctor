import { LEGAL_SOURCE_MANIFEST_VERSION } from "./legalSources";
import type { ControlDefinition, ControlStatus, VerificationClass } from "./types";

const SV = LEGAL_SOURCE_MANIFEST_VERSION;

const ALL_STATUS: ControlStatus[] = [
  "VERIFIED",
  "VIOLATED",
  "PARTIAL",
  "NOT_OBSERVED",
  "NEEDS_CONTEXT",
  "NOT_APPLICABLE",
  "SKIPPED",
  "ERROR"
];

function control(
  partial: Omit<ControlDefinition, "sourceVersion" | "possibleStatuses"> & {
    possibleStatuses?: ControlStatus[];
    sourceVersion?: string;
  }
): ControlDefinition {
  return {
    possibleStatuses: ALL_STATUS,
    sourceVersion: SV,
    ...partial
  };
}

