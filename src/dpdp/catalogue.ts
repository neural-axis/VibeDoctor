export function getControlById(id: string): ControlDefinition | undefined {
  return DPDP_CONTROLS.find((controlDef) => controlDef.id === id);
}

export function controlsByDomain(): Record<string, ControlDefinition[]> {
  const grouped: Record<string, ControlDefinition[]> = {};
  for (const item of DPDP_CONTROLS) {
    grouped[item.domain] = grouped[item.domain] ?? [];
    grouped[item.domain].push(item);
  }
  return grouped;
}

export function controlsForVerificationClass(vc: VerificationClass): ControlDefinition[] {
  return DPDP_CONTROLS.filter((controlDef) => controlDef.verificationClass === vc);
}

